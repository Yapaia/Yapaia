/** Kategoriename in der Sprache der Oberfläche (die Namen in `@yapaia/shared` sind deutsch). */
export function kategorieName(k: { id: string; name: string }, ausgeschrieben = false): string {
  const schluessel = `kat_${k.id}`;
  if (!(schluessel in T.de)) return k.name;
  const name = tx(T, schluessel as keyof typeof T.de);
  return ausgeschrieben ? name : name.charAt(0).toUpperCase() + name.slice(1);
}
